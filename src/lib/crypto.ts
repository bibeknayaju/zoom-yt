import crypto from "node:crypto";

const ALGORITHM = "aes-256-gcm";
const IV_LENGTH = 12;

function getEncryptionKey(): Buffer {
  const secret =
    process.env.TOKEN_ENCRYPTION_KEY ||
    process.env.ENCRYPTION_SECRET ||
    "zoom_youtube_studio_secure_key_2026!";
  return crypto.createHash("sha256").update(secret).digest();
}

/**
 * Encrypts a string using AES-256-GCM.
 * Output format: `iv:tag:ciphertext` (hex encoded)
 */
export function encryptToken(plainText: string): string {
  if (!plainText) return "";
  const key = getEncryptionKey();
  const iv = crypto.randomBytes(IV_LENGTH);
  const cipher = crypto.createCipheriv(ALGORITHM, key, iv);

  let encrypted = cipher.update(plainText, "utf8", "hex");
  encrypted += cipher.final("hex");
  const authTag = cipher.getAuthTag();

  return `${iv.toString("hex")}:${authTag.toString("hex")}:${encrypted}`;
}

/**
 * Decrypts a ciphertext generated by `encryptToken`.
 */
function tryDecryptWithSecret(encryptedString: string, secret: string): string | null {
  try {
    const parts = encryptedString.split(":");
    if (parts.length !== 3) return null;
    const [ivHex, authTagHex, cipherTextHex] = parts;
    const key = crypto.createHash("sha256").update(secret).digest();
    const iv = Buffer.from(ivHex, "hex");
    const authTag = Buffer.from(authTagHex, "hex");

    const decipher = crypto.createDecipheriv(ALGORITHM, key, iv);
    decipher.setAuthTag(authTag);
    let decrypted = decipher.update(cipherTextHex, "hex", "utf8");
    decrypted += decipher.final("utf8");
    return decrypted;
  } catch {
    return null;
  }
}

/**
 * Decrypts a ciphertext generated by `encryptToken`.
 */
export function decryptToken(encryptedString: string): string {
  if (!encryptedString) return "";

  const candidateSecrets = [
    process.env.TOKEN_ENCRYPTION_KEY,
    process.env.ENCRYPTION_SECRET,
    "zoom_youtube_default_dev_key_32b!",
    "zoom_youtube_studio_secure_key_2026!",
  ].filter(Boolean) as string[];

  for (const secret of candidateSecrets) {
    const res = tryDecryptWithSecret(encryptedString, secret);
    if (res !== null) return res;
  }

  throw new Error("Unable to decrypt token: MAC authentication failed or invalid key.");
}
